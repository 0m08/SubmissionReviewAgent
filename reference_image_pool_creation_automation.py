def extract_file_id_from_url(drive_url):
    """
    Extract Google Drive file ID from various URL formats.

    :param drive_url: Google Drive URL
    :return: file ID
    """
    patterns = [
        r'/d/([a-zA-Z0-9-_]+)',
        r'id=([a-zA-Z0-9-_]+)',
        r'/file/d/([a-zA-Z0-9-_]+)',
    ]

    for pattern in patterns:
        match = re.search(pattern, drive_url)
        if match:
            return match.group(1)

    # If no pattern matches, assume the input is already a file ID
    return drive_url

def download_pdf_from_drive(drive, pdf_url):
    """
    Download PDF from Google Drive URL to a temporary file.

    :param drive: GoogleDrive instance
    :param pdf_url: Google Drive URL or file ID
    :return: path to downloaded PDF file
    """
    file_id = extract_file_id_from_url(pdf_url)

    # Get the file
    file = drive.CreateFile({'id': file_id})

    # Create a temporary file
    temp_pdf = tempfile.NamedTemporaryFile(delete=False, suffix='.pdf')
    temp_pdf_path = temp_pdf.name
    temp_pdf.close()

    # Download the file
    file.GetContentFile(temp_pdf_path)

    return temp_pdf_path

def replace_image_links(markdown_text, image_links):
    """
    Replace local image references in markdown with Drive links.
    More aggressive matching approach.
    """
    updated_markdown = markdown_text

    for img_name, drive_link in image_links.items():
        # Get base name without extension
        base_name = os.path.splitext(img_name)[0]

        # Replace ANY occurrence of the image name in parentheses or quotes
        # This is more aggressive but should catch most cases
        updated_markdown = re.sub(
            rf'([(\["\'])([^)\]"\']*?)({re.escape(base_name)}[^)\]"\'/\\]*?)([)\]"\'])',
            rf'\1{drive_link}\4',
            updated_markdown,
            flags=re.IGNORECASE
        )

    return updated_markdown

def upload_markdown_to_drive(drive, markdown_text, course_folder_id, filename='parsed_document.md'):
    """
    Upload markdown file to Google Drive.

    :param drive: GoogleDrive instance
    :param markdown_text: Markdown content
    :param course_folder_id: Parent folder ID
    :param filename: Name for the markdown file
    :return: File ID of uploaded markdown
    """
    # Create temporary markdown file
    temp_md = tempfile.NamedTemporaryFile(mode='w', delete=False, suffix='.md', encoding='utf-8')
    temp_md.write(markdown_text)
    temp_md.close()

    try:
        # Upload to Drive
        file = drive.CreateFile({
            'title': filename,
            'parents': [{'id': course_folder_id}],
            'mimeType': 'text/markdown'
        })
        file.SetContentFile(temp_md.name)
        file.Upload()

        print(f"Uploaded markdown: {filename} (ID: {file['id']})")
        return file['id']

    finally:
        # Clean up temp file
        os.unlink(temp_md.name)

def upload_images_to_drive(drive, images_dict, images_folder_id):
    """
    Upload images to Google Drive and return mapping of local paths to Drive links.

    :param drive: GoogleDrive instance
    :param images_dict: Dictionary of {image_name: image_data} from parser
    :param images_folder_id: Folder ID where images will be uploaded
    :return: Dictionary mapping image names to Drive URLs
    """
    from PIL import Image
    import io

    image_links = {}

    for img_name, img_data in images_dict.items():
        # Create temporary file path
        temp_img_path = tempfile.mktemp(suffix='.png')  # Always use PNG for safety

        try:
            # Handle PIL Image objects
            if isinstance(img_data, Image.Image):
                # Convert to RGB if necessary (handles RGBA, P, L modes)
                if img_data.mode not in ('RGB', 'L'):
                    img_data = img_data.convert('RGB')

                # Save as PNG (most compatible, no encoding issues)
                img_data.save(temp_img_path, format='PNG')

                # Update filename to .png if it wasn't already
                if not img_name.lower().endswith('.png'):
                    img_name = os.path.splitext(img_name)[0] + '.png'

            else:
                # Handle bytes data
                with open(temp_img_path, 'wb') as f:
                    f.write(img_data)

            # Upload to Drive
            file = drive.CreateFile({
                'title': img_name,
                'parents': [{'id': images_folder_id}]
            })
            file.SetContentFile(temp_img_path)
            file.Upload()

            # Make file shareable (anyone with link can view)
            file.InsertPermission({
                'type': 'anyone',
                'value': 'anyone',
                'role': 'reader'
            })

            # Get shareable link
            drive_link = f"https://drive.google.com/uc?export=view&id={file['id']}"
            image_links[img_name] = drive_link

            print(f"Uploaded: {img_name} -> {drive_link}")

        except Exception as e:
            print(f"Error uploading {img_name}: {e}")
            # Try to continue with other images
            continue

        finally:
            # Clean up temp file
            if os.path.exists(temp_img_path):
                os.unlink(temp_img_path)

    return image_links

def format_worksheet(worksheet):
    """
    Apply the following formatting to the given `worksheet`:
    1) Freeze row 1
    2) Bold row 1
    3) Fill row 1 background color with a light gray
    4) All cells font size 8
    5) All cells vertical alignment = middle
    6) All cells text wrapping = clip
    7) Set rows 2+ to a fixed height of 40
    """

    # 1) Freeze row 1
    worksheet.freeze(rows=1, cols=0)

    # 2) Bold row 1 & 3) Light gray background for row 1
    header_format = CellFormat(
        backgroundColor=Color(0.95, 0.95, 0.95),   # Approx. #E0E0E0
        textFormat=TextFormat(bold=True)
    )
    format_cell_range(worksheet, '1', header_format)

    # 4) All cells font size 8, 5) vertical alignment = middle, 6) text wrapping = clip
    # Determine the entire worksheet range dynamically
    total_rows = worksheet.row_count
    total_cols = worksheet.col_count
    bottom_right_cell = rowcol_to_a1(total_rows, total_cols)  # e.g., "Z1000"
    full_range = f"A1:{bottom_right_cell}"

    all_cells_format = CellFormat(
        textFormat=TextFormat(fontSize=8),
        verticalAlignment='TOP',
        wrapStrategy='CLIP'
    )
    format_cell_range(worksheet, full_range, all_cells_format)

    # 7) Set rows 2 through total_rows to a fixed height of 40
    set_row_heights(worksheet, [(f'2:{total_rows}', 40)])

    print("Sheet formatting completed successfully!")

