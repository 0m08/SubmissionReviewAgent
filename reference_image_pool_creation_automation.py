def ensure_automation_columns(worksheet, df):
    """
    Ensure 'Automation Status' and 'Course Sheet Link' columns exist in the worksheet.

    :param worksheet: The worksheet object
    :param df: The dataframe
    :return: Updated dataframe with the columns
    """
    columns_added = []

    # Check and add 'Automation Status' column
    if 'Automation Status' not in df.columns:
        headers = worksheet.row_values(1)
        new_col_index = len(headers) + 1
        worksheet.update_cell(1, new_col_index, 'Automation Status')
        df['Automation Status'] = ''
        columns_added.append('Automation Status')

    # Check and add 'Course Sheet Link' column
    if 'Course Sheet Link' not in df.columns:
        headers = worksheet.row_values(1)
        new_col_index = len(headers) + 1
        worksheet.update_cell(1, new_col_index, 'Course Sheet Link')
        df['Course Sheet Link'] = ''
        columns_added.append('Course Sheet Link')

    if columns_added:
        print(f"✓ Added columns: {', '.join(columns_added)}")

    return df

