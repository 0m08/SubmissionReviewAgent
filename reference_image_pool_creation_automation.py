def process_pdf_to_markdown_with_drive(drive, pdf_url, course_folder_id, output_filename='research_notes.md'):
    """
    Complete workflow: Download PDF, parse, upload images and markdown to Drive.

    :param drive: GoogleDrive instance
    :param pdf_url: Google Drive URL or file ID of the PDF
    :param course_folder_id: Course folder ID where output will be saved
    :param output_filename: Name for the output markdown file
    :return: Dictionary with file IDs and paths
    """
    print("Step 1: Downloading PDF from Drive...")
    pdf_path = download_pdf_from_drive(drive, pdf_url)

    try:
        print("Step 2: Parsing PDF to markdown...")
        markdown_text, images = parse_pdf_to_markdown(pdf_path)

        print("Step 3: Creating images folder in Drive...")
        images_folder_id = create_images_folder_in_drive(drive, course_folder_id)

        print("Step 4: Uploading images to Drive...")
        image_links = upload_images_to_drive(drive, images, images_folder_id)

        print("Step 5: Replacing image links in markdown...")
        updated_markdown = replace_image_links(markdown_text, image_links)

        # VERIFICATION
        if updated_markdown == markdown_text:
            print("WARNING: No replacements were made!")
        else:
            print(f"Markdown was modified ({len(updated_markdown) - len(markdown_text)} character difference)")

        # Check if Drive links are actually in the updated markdown
        drive_link_count = updated_markdown.count('drive.google.com')
        print(f"✓ Found {drive_link_count} Drive links in updated markdown")

        print("Step 6: Uploading markdown to Drive...")
        markdown_file_id = upload_markdown_to_drive(drive, updated_markdown, course_folder_id, output_filename)

        print("\nProcess completed successfully!")
        return {
            'markdown_file_id': markdown_file_id,
            'images_folder_id': images_folder_id,
            'image_count': len(image_links),
            'image_links': image_links,
            'output_filename': output_filename  # ← ADD THIS LINE
        }

    finally:
        # Clean up downloaded PDF
        if os.path.exists(pdf_path):
            os.unlink(pdf_path)

