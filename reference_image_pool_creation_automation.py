def validate_pdf_in_folder(drive, pdf_url, course_folder_id):
    """
    Validate if a PDF exists in the specified course folder.

    :param drive: GoogleDrive instance
    :param pdf_url: Google Drive URL or file ID of the PDF
    :param course_folder_id: Course folder ID to check
    :return: Tuple (exists: bool, file_id: str or None)
    """
    try:
        # Extract file ID from URL
        file_id = extract_file_id_from_url(pdf_url)

        # Get the file metadata
        file = drive.CreateFile({'id': file_id})
        file.FetchMetadata(fields='parents,title')

        # Check if the file exists
        if not file:
            return False, None

        # Get parent folder IDs
        parents = file.get('parents', [])
        parent_ids = [parent['id'] for parent in parents]

        # Check if course_folder_id is in the parents
        if course_folder_id in parent_ids:
            return True, file_id
        else:
            return False, None

    except Exception as e:
        print(f"Error validating PDF: {str(e)}")
        return False, None

