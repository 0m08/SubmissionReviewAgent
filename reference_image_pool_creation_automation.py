def upload_folder_to_drive(local_folder_path, parent_drive_folder_id, drive):
    # Always use 'chroma_graphics_db' as the folder name in Google Drive for consistency
    folder_name = "chroma_graphics_db"

    # Step 1: Create a folder on Drive
    folder_metadata = {
        "title": folder_name,
        "parents": [{"id": parent_drive_folder_id}],
        "mimeType": "application/vnd.google-apps.folder",
    }
    drive_folder = drive.CreateFile(folder_metadata)
    drive_folder.Upload()
    drive_folder_id = drive_folder["id"]

    # Step 2: Recursively upload contents
    for root, dirs, files in os.walk(local_folder_path):
        rel_path = os.path.relpath(root, local_folder_path)
        current_folder_id = drive_folder_id

        # Maintain folder structure
        if rel_path != ".":
            path_parts = rel_path.split(os.sep)
            for part in path_parts:
                folder_list = drive.ListFile({
                    "q": f"title='{part}' and '{current_folder_id}' in parents and mimeType='application/vnd.google-apps.folder' and trashed=false"
                }).GetList()
                if folder_list:
                    current_folder_id = folder_list[0]["id"]
                else:
                    subfolder_metadata = {
                        "title": part,
                        "parents": [{"id": current_folder_id}],
                        "mimeType": "application/vnd.google-apps.folder",
                    }
                    subfolder = drive.CreateFile(subfolder_metadata)
                    subfolder.Upload()
                    current_folder_id = subfolder["id"]

        # Upload files in current directory
        for file_name in files:
            file_path = os.path.join(root, file_name)
            f = drive.CreateFile({"title": file_name, "parents": [{"id": current_folder_id}]})
            f.SetContentFile(file_path)
            f.Upload()

def extract_file_id_from_url(url: str) -> str:
    """Extract Drive file id from a standard Drive URL."""
    if not url:
        return ""
    patterns = [
        r"https://drive\.google\.com/file/d/([a-zA-Z0-9_-]+)",
        r"https://drive\.google\.com/open\?id=([a-zA-Z0-9_-]+)",
        r"https://drive\.google\.com/uc\?id=([a-zA-Z0-9_-]+)",
        r"https://drive\.google\.com/uc\?export=download&id=([a-zA-Z0-9_-]+)",
        r"https://drive\.google\.com/uc\?export=view&id=([a-zA-Z0-9_-]+)",
    ]
    for pattern in patterns:
        match = re.match(pattern, url)
        if match:
            return match.group(1)
    return ""


def get_image_embedding(image_path: str) -> List[float]:
    """Generates image embedding using Cohere embed-v4.0."""
    with open(image_path, "rb") as f:
        enc_img = base64.b64encode(f.read()).decode("utf-8")
        enc_img = f"data:image/jpeg;base64,{enc_img}"

    response = co.embed(
        model="embed-v4.0",
        images=[enc_img],
        input_type="image",
        embedding_types=["float"],
    )
    return response.embeddings.float[0]


def get_text_embedding(text: str) -> List[float]:
    """Generates text embedding using Cohere embed-english-v3.0."""
    response = co.embed(
        model="embed-english-v3.0",
        texts=[text],
        input_type="search_document",
        embedding_types=["float"],
    )
    return response.embeddings.float[0]

def build_image_vector_store(drive, image_links, vector_store_drive_id):
    """
    Builds the vector store with simplified hierarchy and uploads to Drive.
    Structure: Vectorstore files -> chroma_graphics_db -> [Chroma Indexing & Data Files]
    Collections: text_embeddings, image_embeddings (compatible with create_vectorstore.py)
    """
    # 1. Setup local paths for the hierarchy
    local_root = f"/tmp/vector_assets_{uuid.uuid4().hex[:8]}"
    db_root = os.path.join(local_root, "chroma_graphics_db")

    if os.path.exists(local_root):
        shutil.rmtree(local_root)

    # Ensure the database root exists
    os.makedirs(db_root, exist_ok=True)

    print(f"Initializing ChromaDB at {db_root}...")

    # Chroma is initialized directly in chroma_graphics_db
    client = Client(Settings(is_persistent=True, persist_directory=db_root))
    text_collection = client.get_or_create_collection(name="text_embeddings")
    image_collection = client.get_or_create_collection(name="image_embeddings")

    print(f"Processing {len(image_links)} images...")

    for img_name, drive_url in image_links.items():
        file_id = extract_file_id_from_url(drive_url)
        if not file_id:
            print(f"❌ Skipping (no file id): {img_name}")
            continue
        success = False

        for attempt in range(4):
            temp_img_path = None
            try:
                temp_img_path = tempfile.mktemp(suffix=".png")
                file = drive.CreateFile({"id": file_id})
                file.GetContentFile(temp_img_path)

                image_embedding = get_image_embedding(temp_img_path)
                text_embedding = get_text_embedding(img_name)

                with Image.open(temp_img_path) as img:
                    phash = str(imagehash.phash(img))

                metadata = {
                    "image_id": file_id,
                    "name": img_name,
                    "drive_url": drive_url,
                    "mime_type": "",
                    "description": img_name,
                    "image_type": "",
                    "image_title": img_name,
                    "folder_id": vector_store_drive_id,
                    "embedding_type": "image",
                    "phash": phash,
                }

                image_collection.add(
                    ids=[f"img_{file_id}"],
                    embeddings=[image_embedding],
                    metadatas=[metadata],
                    documents=["image_embedding_only"],
                )

                text_collection.add(
                    ids=[f"txt_{file_id}"],
                    embeddings=[text_embedding],
                    metadatas=[{**metadata, "embedding_type": "text"}],
                    documents=[img_name],
                )

                print(f"✓ Embedded: {img_name}")
                success = True
                if os.path.exists(temp_img_path):
                    os.unlink(temp_img_path)
                if success:
                    break
            except Exception as e:
                if temp_img_path and os.path.exists(temp_img_path):
                    os.unlink(temp_img_path)
                if "IncompleteRead" in str(e) or "EOF" in str(e):
                    time.sleep(3 * (attempt + 1))
                else:
                    print(f"❌ Failed to embed {img_name}: {e}")
                    break

    print("Uploading structured Vectorstore files to Drive...")
    # Upload everything inside local_root so 'chroma_graphics_db' is the top folder
    upload_folder_to_drive(db_root, vector_store_drive_id, drive)
    print("✅ Hierarchical Vector Store built and uploaded successfully.")

