def get_markdown_from_drive(drive, course_folder_id, markdown_filename):
    """
    Read the markdown file from Google Drive.

    :param drive: GoogleDrive instance
    :param course_folder_id: Course folder ID
    :param markdown_filename: Name of the markdown file
    :return: Markdown text content
    """
    # Search for the markdown file in the course folder
    query = f"'{course_folder_id}' in parents and title='{markdown_filename}' and trashed=false"
    file_list = drive.ListFile({'q': query}).GetList()

    if not file_list:
        raise FileNotFoundError(f"Markdown file '{markdown_filename}' not found in course folder")

    file = file_list[0]

    # Download to temporary file
    temp_md = tempfile.NamedTemporaryFile(delete=False, suffix='.md', mode='w+', encoding='utf-8')
    temp_md.close()

    file.GetContentFile(temp_md.name)

    # Read content
    with open(temp_md.name, 'r', encoding='utf-8') as f:
        content = f.read()

    # Clean up
    os.unlink(temp_md.name)

    return content

